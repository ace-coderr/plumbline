/**
 * Writes packages/shared/src/addresses.ts. The deploy script is the only caller; every package
 * imports addresses from the shared module instead of copying them.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export interface TokenInfo {
  address: `0x${string}`;
  symbol: string;
  name: string;
  decimals: number;
}

/** The PLUMBUSD faucet (contracts/src/test/PlumbFaucet.sol). Demo only. */
export interface FaucetInfo {
  address: `0x${string}`;
  token: `0x${string}`;
  /** Raw token units per claim, as a decimal string. */
  amount: string;
  /** Seconds between claims for one address. */
  cooldown: number;
  deployBlock: number;
  deployedAt: string;
}

/**
 * The first campaigns and router contracts (v1). Their probe gate counted the parent chain's blocks, so
 * it opened about every two minutes; v2 counts Orbit L2 blocks. v1 is still on-chain and still holds its
 * campaigns, bonds and unclaimed rewards, so the app keeps reading it.
 */
export interface LegacyDeployment {
  campaigns: `0x${string}`;
  router: `0x${string}`;
  deployBlock: number;
  deployedAt: string;
  /** Git tag of the source verified on the explorer for these two contracts. */
  sourceTag: string;
}

/** Where the current (v2) campaigns and router were deployed, and the source they were verified from. */
export interface CurrentDeployment {
  deployBlock: number;
  deployedAt: string;
  sourceTag: string;
}

export interface DeploymentRecord {
  chainId: number;
  deployed: boolean;
  deployBlock: number;
  deployedAt: string;
  deployer: `0x${string}`;
  contracts: {
    factory: `0x${string}`;
    router: `0x${string}`;
    campaigns: `0x${string}`;
  };
  params: { maxAge: number; withdrawDelay: number };
  tokens: Record<string, TokenInfo>;
  /**
   * Mintable stand-ins deployed by the seed for demo markets (see DemoQuoteToken.sol). Never
   * canonical, always labelled "demo asset" in the UI.
   */
  demoTokens: Record<string, TokenInfo>;
  /** Present once the faucet has been deployed. */
  faucet?: FaucetInfo;
  /** Present once campaigns and router were redeployed: `contracts` then holds v2 and this holds v1. */
  legacy?: LegacyDeployment;
  /** Present with `legacy`: provenance of the v2 campaigns and router in `contracts`. */
  v2?: CurrentDeployment;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
export const ADDRESSES_PATH = join(root, "packages/shared/src/addresses.ts");

export function writeAddresses(d: DeploymentRecord): void {
  const header =
    "// Generated by scripts/deploy.ts. Do not edit by hand: redeploy to change.\n" +
    "// Token decimals were read on-chain at deploy time.\n\n";
  const body = `export const deployment = ${JSON.stringify(d, null, 2)} as const;\n\nexport type Deployment = typeof deployment;\n`;
  writeFileSync(ADDRESSES_PATH, header + body);
}
