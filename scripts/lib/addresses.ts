/**
 * Writes packages/shared/src/addresses.ts. The deploy script is the only caller; every package
 * imports addresses from the shared module instead of copying them.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export interface TokenInfo {
  address: `0x${string}`;
  symbol: string;
  name: string;
  decimals: number;
}

export interface DeploymentRecord {
  chainId: number;
  deployed: boolean;
  deployBlock: number;
  deployedAt: string;
  deployer: `0x${string}`;
  contracts: {
    factory: `0x${string}`;
    router: `0x${string}`;
    campaigns: `0x${string}`;
  };
  params: { maxAge: number; withdrawDelay: number };
  tokens: Record<string, TokenInfo>;
  /**
   * Mintable stand-ins deployed by the seed for demo markets (see DemoQuoteToken.sol). Never
   * canonical, always labelled "demo asset" in the UI.
   */
  demoTokens: Record<string, TokenInfo>;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
export const ADDRESSES_PATH = join(root, "packages/shared/src/addresses.ts");

export function writeAddresses(d: DeploymentRecord): void {
  const header =
    "// Generated by scripts/deploy.ts. Do not edit by hand: redeploy to change.\n" +
    "// Token decimals were read on-chain at deploy time.\n\n";
  const body = `export const deployment = ${JSON.stringify(d, null, 2)} as const;\n\nexport type Deployment = typeof deployment;\n`;
  writeFileSync(ADDRESSES_PATH, header + body);
}
