/**
 * Generates typed ABI modules for the shared package from Foundry build output.
 * Run after `forge build`: `pnpm abis`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "packages/shared/src/abis");
mkdirSync(outDir, { recursive: true });

const contracts = ["PlumbQuote", "PlumbQuoteFactory", "PlumbRouter", "PlumbCampaigns", "PlumbFaucet"] as const;

interface ForgeArtifact {
  abi: unknown[];
}

const exportsList: string[] = [];
for (const name of contracts) {
  const artifactPath = join(root, "contracts/out", `${name}.sol`, `${name}.json`);
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as ForgeArtifact;
  const ident = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
  const body = JSON.stringify(artifact.abi, null, 2);
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/gen-abis.ts from contracts/out. Do not edit.\nexport const ${ident} = ${body} as const;\n`,
  );
  exportsList.push(`export { ${ident} } from "./${name}.js";`);
}

writeFileSync(
  join(outDir, "index.ts"),
  `// Generated by scripts/gen-abis.ts. Do not edit.\n${exportsList.join("\n")}\nexport { wrappedNativeAbi } from "./wrappedNative.js";\n`,
);
console.log(`wrote ${contracts.length} ABIs to ${outDir}`);
